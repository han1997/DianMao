#!/usr/bin/env python3
"""Convert the prototype's inline SVG icon sprite into Compose ImageVector code.

The confirmed prototype (design/mockup/index.html) defines its icons as stroke
SVGs (1.7px round-cap lines) while the app uses Material Filled icons, a visible
pixel-level divergence. This script mechanically rebuilds the prototype icons as
Kotlin ImageVectors so the app can render the exact same artwork.

Usage: python design/mockup/tools/gen_icons.py > app/src/main/java/fun/han1997/dianmao/ui/theme/DianMaoIcons.kt
"""
import re
import sys

SRC = "design/mockup/index.html"


def camel(name: str) -> str:
    # i-arrow-back -> ArrowBack ; i-chev-right -> ChevRight
    return "".join(part.capitalize() for part in name[2:].split("-"))


def main() -> None:
    html = open(SRC, encoding="utf-8").read()
    syms = re.findall(r'<symbol id="(i-[a-z-]+)" viewBox="([^"]+)">(.*?)</symbol>', html, re.S)
    out = []
    out.append("package `fun`.han1997.dianmao")
    out.append("")
    out.append("// GENERATED by design/mockup/tools/gen_icons.py -- do not edit by hand.")
    out.append("// Source of truth: design/mockup/index.html (confirmed prototype).")
    out.append("// These vectors reproduce the prototype's thin round-cap stroke icons so")
    out.append("// the app matches the prototype pixel-for-pixel instead of using Material")
    out.append("// Filled icons.")
    out.append("")
    out.append("import androidx.compose.ui.graphics.Color")
    out.append("import androidx.compose.ui.graphics.SolidColor")
    out.append("import androidx.compose.ui.graphics.StrokeCap")
    out.append("import androidx.compose.ui.graphics.StrokeJoin")
    out.append("import androidx.compose.ui.graphics.vector.ImageVector")
    out.append("import androidx.compose.ui.graphics.vector.PathParser")

    out.append("import androidx.compose.ui.unit.dp")
    out.append("")
    out.append("object DianMaoIcons {")

    def emit_path(d: str, stroke: float, filled: bool, indent: str) -> str:
        base = (f'{indent}addPath(\n'
                f'{indent}    pathData = PathParser().parsePathString("{d}").toNodes(),\n')
        if filled:
            return base + f'{indent}    fill = SolidColor(Color.Black)\n{indent})'
        return (base
                + f'{indent}    fill = null,\n'
                + f'{indent}    stroke = SolidColor(Color.Black),\n'
                + f'{indent}    strokeLineWidth = {stroke}f,\n'
                + f'{indent}    strokeLineCap = StrokeCap.Round,\n'
                + f'{indent}    strokeLineJoin = StrokeJoin.Round\n'
                + f'{indent})')

    for name, _vb, body in syms:
        prop = camel(name)
        gm = re.search(r'<g([^>]*)>', body)
        g_attrs = gm.group(1) if gm else ""
        group_fill = "fill=\"currentColor\"" in g_attrs or "fill=\"currentColor\"" in body
        sm = re.search(r'stroke-width="([\d.]+)"', body)
        stroke = sm.group(1) if sm else "1.7"
        paths = []
        for cm in re.finditer(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"', body):
            cx, cy, r = cm.groups()
            d = (f"M{cx},{float(cy)-float(r)} a{r},{r} 0 1,0 0,{float(r)*2} "
                 f"a{r},{r} 0 1,0 0,-{float(r)*2}")
            paths.append(emit_path(d, float(stroke), group_fill, "            "))
        for rm in re.finditer(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"(?: rx="([\d.]+)")?', body):
            x, y, w, h = map(float, rm.groups()[:4])
            rx = float(rm.group(5)) if rm.group(5) else 0.0
            if rx > 0:
                d = (f"M{x+rx},{y} L{x+w-rx},{y} Q{x+w},{y} {x+w},{y+rx} "
                     f"L{x+w},{y+h-rx} Q{x+w},{y+h} {x+w-rx},{y+h} "
                     f"L{x+rx},{y+h} Q{x},{y+h} {x},{y+h-rx} "
                     f"L{x},{y+rx} Q{x},{y} {x+rx},{y} Z")
            else:
                d = f"M{x},{y} L{x+w},{y} L{x+w},{y+h} L{x},{y+h} Z"
            paths.append(emit_path(d, float(stroke), group_fill, "            "))
        for pm in re.finditer(r'<path[^>]*\bd="([^"]+)"', body):
            paths.append(emit_path(pm.group(1), float(stroke), group_fill, "            "))
        out.append(f"\n    val {prop}: ImageVector by lazy {{")
        out.append(f'        ImageVector.Builder(name = "{prop}", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)')
        if paths:
            out.append("            .apply {")
            out.extend(paths)
            out.append("            }")
        out.append("            .build()")
        out.append("    }")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()